-- SS data-shape extractor (read-only, aggregates only).
--
-- Purpose: profile numbers for ss-synthetic-generator.sql, so the synthetic SS database has the
-- same shape as production. Covers only what the EX/AG/AD/SP/OD/LX extracts do not already give:
-- time-of-day, duration, weekday, per-location volume, per-sheriff workload percentiles,
-- assignment patterns, and field presence.
--
-- Privacy: no row-level data. No names, emails, IDs, badge numbers, photos, or free text.
-- Text columns are reported as null/blank rates and length bands only. Location and lookup names
-- are public reference data. Any count from 1 to 4 is shown as "<5", and its share % and median
-- are left blank. Rank text values held by fewer than 5 users are grouped as "other". Per-sheriff
-- measures are percentiles over groups of 5 or more sheriffs; no maximums.
-- SH-07 additionally withholds ALL field-presence counts for a table if any of its cells is 1-4,
-- including zeros and repeated row totals. "suppressed" can therefore mean any non-negative count,
-- not just 1-4. SH-08 counts are also withheld when User field-presence counts are withheld.
-- This conservative rule protects field-presence partitions, not arbitrary linkage to other
-- extracts or a general disclosure assessment of the other aggregate sections.
--
-- Target: legacy Sheriff Scheduling PostgreSQL database (EF Core quoted PascalCase tables).
-- Output: GitHub-flavoured Markdown written to ss-shape-extracts.md.
--
-- Run from documentation/data-migration/ss-job-notes with a read-only account:
--   psql "host=<host> port=<port> dbname=<db> user=<read-only user>" -X -q -f ss-shape-extractor.sql -o ss-shape-extracts.md
--
-- psql only (backslash lines are psql client commands). PostgreSQL 12 or later.
--
-- Scope: rows starting on or after 2015-01-01. Local times use the row Timezone, or
-- America/Vancouver when the value is missing or unknown. Live = ExpiryDate IS NULL.
--
-- Safety: one REPEATABLE READ READ ONLY transaction, rolled back at the end. No temp objects,
-- functions, or writes.

\set ON_ERROR_STOP on
\set QUIET on
\pset pager off
\pset format unaligned
\pset tuples_only on
\pset footer off
\pset fieldsep ' | '
\pset null '(null)'

\set tz 'CASE WHEN e.tz IN (SELECT name FROM pg_timezone_names) THEN e.tz ELSE ''America/Vancouver'' END'
\set ev '(SELECT ''Shift''::text AS tbl, "LocationId" AS loc, "SheriffId" AS sid, "StartDate" AS st, "EndDate" AS en, "ExpiryDate" AS ex, "Timezone" AS tz FROM "Shift" UNION ALL SELECT ''Duty'', "LocationId", NULL::uuid, "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "Duty" UNION ALL SELECT ''DutySlot'', "LocationId", "SheriffId", "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "DutySlot" UNION ALL SELECT ''SheriffLeave'', NULL::int, "SheriffId", "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "SheriffLeave" UNION ALL SELECT ''SheriffTraining'', NULL::int, "SheriffId", "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "SheriffTraining" UNION ALL SELECT ''SheriffAwayLocation'', "LocationId", "SheriffId", "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "SheriffAwayLocation" UNION ALL SELECT ''SheriffActingRank'', NULL::int, "SheriffId", "StartDate", "EndDate", "ExpiryDate", "Timezone" FROM "SheriffActingRank")'
\set sup 'CASE WHEN n BETWEEN 1 AND 4 THEN ''<5'' ELSE n::text END'

BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;

SET LOCAL TimeZone = 'UTC';
SET LOCAL statement_timeout = '30min';
SET LOCAL lock_timeout = '5s';

\qecho '# SS Data-Shape Extracts'
\qecho
\qecho 'Generated by ss-shape-extractor.sql in one read-only snapshot. Aggregates only; counts 1-4 shown as <5. Do not edit by hand; re-run to refresh.'
\qecho
\qecho 'Section | Question'
\qecho '--- | ---'
\qecho 'SH-01 | How much live data does each location hold per year?'
\qecho 'SH-02 | At what local hour do rows start, per table?'
\qecho 'SH-03 | How long are rows, per table?'
\qecho 'SH-04 | Which weekdays do rows start on, per table?'
\qecho 'SH-05 | How much does a typical sheriff carry per year (percentiles)?'
\qecho 'SH-06 | What weekday and time patterns do assignments use?'
\qecho 'SH-07 | How often are optional and text fields filled, and how long are texts?'
\qecho 'SH-08 | How are users, roles and home locations distributed?'

\qecho
\qecho '## SH-00 Run Metadata'
\qecho
\qecho 'Item | Value'
\qecho '--- | ---'
SELECT k, v FROM (VALUES
    (1, 'Database', current_database()),
    (2, 'Extracted at (UTC)', to_char(now(), 'YYYY-MM-DD HH24:MI:SS')),
    (3, 'Server version', current_setting('server_version')),
    (4, 'Transaction read only', current_setting('transaction_read_only')),
    (5, 'Latest EF migration', (SELECT max("MigrationId") FROM "__EFMigrationsHistory"))
) AS t(o, k, v) ORDER BY o;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-01 Live Rows Per Location And Start Year'
\qecho
\qecho 'Live rows only. Leave, training and acting rank rows are counted at the sheriff home location. Sheriffs = enabled sheriffs homed there now.'
\qecho
\qecho 'Location | Year | Shifts | Duties | Duty slots | Leave | Training | Away (to here) | Acting rank | Sheriffs homed'
\qecho '--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---:'
WITH e AS (
    SELECT e.tbl, coalesce(e.loc, u."HomeLocationId") AS loc,
           extract(year FROM e.st AT TIME ZONE :tz)::int AS yr
    FROM :ev e LEFT JOIN "User" u ON u."Id" = e.sid
    WHERE e.ex IS NULL AND e.st >= timestamptz '2015-01-01 00:00:00+00'
), c AS (
    SELECT loc, yr,
           count(*) FILTER (WHERE tbl = 'Shift') AS s, count(*) FILTER (WHERE tbl = 'Duty') AS d,
           count(*) FILTER (WHERE tbl = 'DutySlot') AS ds, count(*) FILTER (WHERE tbl = 'SheriffLeave') AS l,
           count(*) FILTER (WHERE tbl = 'SheriffTraining') AS t, count(*) FILTER (WHERE tbl = 'SheriffAwayLocation') AS a,
           count(*) FILTER (WHERE tbl = 'SheriffActingRank') AS r
    FROM e GROUP BY loc, yr
), h AS (
    SELECT "HomeLocationId" AS loc, count(*) AS n FROM "User"
    WHERE "Discriminator" = 'Sheriff' AND "IsEnabled" GROUP BY 1
)
SELECT coalesce(l."Name", '(none)'), c.yr,
       (SELECT :sup FROM (SELECT c.s AS n) x), (SELECT :sup FROM (SELECT c.d AS n) x),
       (SELECT :sup FROM (SELECT c.ds AS n) x), (SELECT :sup FROM (SELECT c.l AS n) x),
       (SELECT :sup FROM (SELECT c.t AS n) x), (SELECT :sup FROM (SELECT c.a AS n) x),
       (SELECT :sup FROM (SELECT c.r AS n) x), (SELECT :sup FROM (SELECT coalesce(h.n, 0) AS n) x)
FROM c LEFT JOIN "Location" l ON l."Id" = c.loc LEFT JOIN h ON h.loc = c.loc
ORDER BY 1, 2;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-02 Local Start Hour By Table'
\qecho
\qecho 'Live rows. Share = percent of the table live rows.'
\qecho
\qecho 'Table | Local start hour | Rows | Share %'
\qecho '--- | ---: | ---: | ---:'
WITH e AS (
    SELECT e.tbl, extract(hour FROM e.st AT TIME ZONE :tz)::int AS hr
    FROM :ev e WHERE e.ex IS NULL AND e.st >= timestamptz '2015-01-01 00:00:00+00'
), c AS (SELECT tbl, hr, count(*) AS n, sum(count(*)) OVER (PARTITION BY tbl) AS tot FROM e GROUP BY 1, 2)
SELECT tbl, hr, :sup, CASE WHEN n >= 5 THEN round(100.0 * n / tot, 2) END FROM c ORDER BY 1, 2;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-03 Duration Bands By Table'
\qecho
\qecho 'Live rows. Duration = EndDate - StartDate. Bands are lower-inclusive.'
\qecho
\qecho 'Table | Band | Rows | Share % | Median minutes in band'
\qecho '--- | --- | ---: | ---: | ---:'
WITH e AS (
    SELECT e.tbl, extract(epoch FROM e.en - e.st) / 60.0 AS m
    FROM :ev e WHERE e.ex IS NULL AND e.st >= timestamptz '2015-01-01 00:00:00+00'
), b AS (
    SELECT tbl, m, CASE WHEN m <= 0 THEN '00 <=0' WHEN m < 60 THEN '01 <1h' WHEN m < 240 THEN '02 1-4h'
                        WHEN m < 480 THEN '03 4-8h' WHEN m = 480 THEN '04 =8h' WHEN m <= 510 THEN '05 8-8.5h'
                        WHEN m < 600 THEN '06 8.5-10h' WHEN m < 720 THEN '07 10-12h' WHEN m < 1440 THEN '08 12-24h'
                        WHEN m < 2880 THEN '09 1-2d' WHEN m < 10080 THEN '10 2-7d' WHEN m < 43200 THEN '11 7-30d'
                        ELSE '12 >=30d' END AS band
    FROM e
), c AS (
    SELECT tbl, band, count(*) AS n, sum(count(*)) OVER (PARTITION BY tbl) AS tot,
           percentile_cont(0.5) WITHIN GROUP (ORDER BY m) AS med
    FROM b GROUP BY 1, 2
)
SELECT tbl, band, :sup, CASE WHEN n >= 5 THEN round(100.0 * n / tot, 2) END, CASE WHEN n < 5 THEN NULL ELSE round(med::numeric, 0) END
FROM c ORDER BY 1, 2;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-04 Local Start Weekday By Table'
\qecho
\qecho 'Live rows. ISO weekday: 1 = Monday, 7 = Sunday.'
\qecho
\qecho 'Table | Weekday | Rows | Share %'
\qecho '--- | ---: | ---: | ---:'
WITH e AS (
    SELECT e.tbl, extract(isodow FROM e.st AT TIME ZONE :tz)::int AS dw
    FROM :ev e WHERE e.ex IS NULL AND e.st >= timestamptz '2015-01-01 00:00:00+00'
), c AS (SELECT tbl, dw, count(*) AS n, sum(count(*)) OVER (PARTITION BY tbl) AS tot FROM e GROUP BY 1, 2)
SELECT tbl, dw, :sup, CASE WHEN n >= 5 THEN round(100.0 * n / tot, 2) END FROM c ORDER BY 1, 2;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-05 Per-Sheriff Workload Per Year (Percentiles)'
\qecho
\qecho 'Live rows per sheriff per local start year, over sheriffs with at least one row of that table in the year. Locations = distinct shift locations. Groups under 5 sheriffs are suppressed.'
\qecho
\qecho 'Table | Year | Sheriffs | p10 | p50 | p90'
\qecho '--- | ---: | ---: | ---: | ---: | ---:'
WITH e AS (
    SELECT e.tbl, e.sid, e.loc, extract(year FROM e.st AT TIME ZONE :tz)::int AS yr
    FROM :ev e WHERE e.ex IS NULL AND e.sid IS NOT NULL AND e.st >= timestamptz '2015-01-01 00:00:00+00'
), p AS (
    SELECT tbl, yr, sid, count(*)::numeric AS v FROM e GROUP BY 1, 2, 3
    UNION ALL
    SELECT 'Shift locations', yr, sid, count(DISTINCT loc)::numeric FROM e WHERE tbl = 'Shift' GROUP BY 2, 3
), q AS (
    SELECT tbl, yr, count(*) AS n,
           percentile_cont(0.1) WITHIN GROUP (ORDER BY v) AS p10,
           percentile_cont(0.5) WITHIN GROUP (ORDER BY v) AS p50,
           percentile_cont(0.9) WITHIN GROUP (ORDER BY v) AS p90
    FROM p GROUP BY 1, 2
)
SELECT tbl, yr, :sup,
       CASE WHEN n >= 5 THEN round(p10::numeric, 1) END, CASE WHEN n >= 5 THEN round(p50::numeric, 1) END,
       CASE WHEN n >= 5 THEN round(p90::numeric, 1) END
FROM q ORDER BY 1, 2;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-06 Assignment Patterns'
\qecho
\qecho 'Live assignments. Mask = Mon..Sun weekday flags. Start/End are the Assignment interval columns (local time of day). Ad hoc = AdhocStartDate set.'
\qecho
\qecho 'Lookup type | Weekday mask | Start | End | Ad hoc | Assignments | Live duties last 12 months'
\qecho '--- | --- | --- | --- | --- | ---: | ---:'
WITH a AS (
    SELECT a."Id", lc."Type" AS typ,
           (CASE WHEN a."Monday" THEN 'M' ELSE '-' END) || (CASE WHEN a."Tuesday" THEN 'T' ELSE '-' END) ||
           (CASE WHEN a."Wednesday" THEN 'W' ELSE '-' END) || (CASE WHEN a."Thursday" THEN 'T' ELSE '-' END) ||
           (CASE WHEN a."Friday" THEN 'F' ELSE '-' END) || (CASE WHEN a."Saturday" THEN 'S' ELSE '-' END) ||
           (CASE WHEN a."Sunday" THEN 'S' ELSE '-' END) AS mask,
           to_char(a."Start", 'HH24:MI') AS st, to_char(a."End", 'HH24:MI') AS en,
           a."AdhocStartDate" IS NOT NULL AS adhoc
    FROM "Assignment" a JOIN "LookupCode" lc ON lc."Id" = a."LookupCodeId"
    WHERE a."ExpiryDate" IS NULL
), d AS (
    SELECT "AssignmentId", count(*) AS n FROM "Duty"
    WHERE "ExpiryDate" IS NULL AND "StartDate" >= now() - interval '12 months' AND "StartDate" < now()
    GROUP BY 1
), g AS (
    SELECT a.typ, a.mask, a.st, a.en, a.adhoc, count(*) AS n, coalesce(sum(d.n), 0) AS dn
    FROM a LEFT JOIN d ON d."AssignmentId" = a."Id" GROUP BY 1, 2, 3, 4, 5
)
SELECT typ, mask, st, en, CASE WHEN adhoc THEN 'yes' ELSE 'no' END, :sup,
       CASE WHEN dn BETWEEN 1 AND 4 THEN '<5' ELSE dn::text END
FROM g ORDER BY 1, n DESC, 2, 3, 4;

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-07 Field Presence And Text Length'
\qecho
\qecho 'All rows. Blank = empty or whitespace only. Length bands describe non-blank values; no text is shown. If any cell is 1-4, all field-presence counts for that table (including zeros and totals) are suppressed.'
\qecho
\qecho 'Table.Column | Rows | Null | Blank | Len 1-20 | Len 21-100 | Len 101-500 | Len >500'
\qecho '--- | ---: | ---: | ---: | ---: | ---: | ---: | ---:'
WITH t(col, v) AS (
    SELECT 'Assignment.Name', "Name"::text FROM "Assignment"
    UNION ALL SELECT 'Assignment.Comment', "Comment"::text FROM "Assignment"
    UNION ALL SELECT 'Assignment.ExpiryReason', "ExpiryReason" FROM "Assignment"
    UNION ALL SELECT 'Duty.Comment', "Comment"::text FROM "Duty"
    UNION ALL SELECT 'Shift.Comment', "Comment"::text FROM "Shift"
    UNION ALL SELECT 'SheriffLeave.Comment', "Comment"::text FROM "SheriffLeave"
    UNION ALL SELECT 'SheriffLeave.ExpiryReason', "ExpiryReason" FROM "SheriffLeave"
    UNION ALL SELECT 'SheriffTraining.Comment', "Comment"::text FROM "SheriffTraining"
    UNION ALL SELECT 'SheriffTraining.Note', "Note"::text FROM "SheriffTraining"
    UNION ALL SELECT 'SheriffTraining.ExpiryReason', "ExpiryReason" FROM "SheriffTraining"
    UNION ALL SELECT 'SheriffAwayLocation.Comment', "Comment"::text FROM "SheriffAwayLocation"
    UNION ALL SELECT 'SheriffActingRank.Comment', "Comment"::text FROM "SheriffActingRank"
    UNION ALL SELECT 'User.Email', "Email" FROM "User"
    UNION ALL SELECT 'User.BadgeNumber', "BadgeNumber" FROM "User"
    UNION ALL SELECT 'User.Rank', "Rank" FROM "User"
    UNION ALL SELECT 'User.IdirName', "IdirName" FROM "User"
    UNION ALL SELECT 'User.IdirId', "IdirId"::text FROM "User"
    UNION ALL SELECT 'User.KeyCloakId', "KeyCloakId"::text FROM "User"
    UNION ALL SELECT 'User.Photo (bytes)', CASE WHEN "Photo" IS NULL THEN NULL WHEN length("Photo") = 0 THEN '' ELSE repeat('x', least(length("Photo"), 501)) END FROM "User"
    UNION ALL SELECT 'User.Gender', "Gender"::text FROM "User"
    UNION ALL SELECT 'User.LastLogin', "LastLogin"::text FROM "User"
    UNION ALL SELECT 'User.Excused (true)', CASE WHEN "Excused" THEN 'y' END FROM "User"
    UNION ALL SELECT 'User.IsEnabled (true)', CASE WHEN "IsEnabled" THEN 'y' END FROM "User"
    UNION ALL SELECT 'SheriffTraining.TrainingCertificationExpiry', "TrainingCertificationExpiry"::text FROM "SheriffTraining"
    UNION ALL SELECT 'SheriffTraining.FirstNotice (true)', CASE WHEN "FirstNotice" THEN 'y' END FROM "SheriffTraining"
), c AS (
    SELECT col, count(*) AS r, count(*) FILTER (WHERE v IS NULL) AS nl,
           count(*) FILTER (WHERE v IS NOT NULL AND v ~ '^\s*$') AS bl,
           count(*) FILTER (WHERE v !~ '^\s*$' AND length(v) <= 20) AS l1,
           count(*) FILTER (WHERE length(v) BETWEEN 21 AND 100 AND v !~ '^\s*$') AS l2,
           count(*) FILTER (WHERE length(v) BETWEEN 101 AND 500 AND v !~ '^\s*$') AS l3,
           count(*) FILTER (WHERE length(v) > 500 AND v !~ '^\s*$') AS l4
    FROM t GROUP BY 1
), p AS (
    -- Totals repeat across columns, and SH-08 partitions the User total again. Withholding
    -- only a total, or leaving several "<5" cells whose sum is known, can still disclose them.
    -- Hide the entire table's histograms without identifying primary vs complementary cells.
    SELECT c.*, bool_or(
        r BETWEEN 1 AND 4 OR nl BETWEEN 1 AND 4 OR bl BETWEEN 1 AND 4 OR
        l1 BETWEEN 1 AND 4 OR l2 BETWEEN 1 AND 4 OR l3 BETWEEN 1 AND 4 OR l4 BETWEEN 1 AND 4
    ) OVER (PARTITION BY split_part(col, '.', 1)) AS hide
    FROM c
)
SELECT coalesce(string_agg(col || ' | ' || CASE WHEN hide
           THEN 'suppressed | suppressed | suppressed | suppressed | suppressed | suppressed | suppressed'
           ELSE concat_ws(' | ', r, nl, bl, l1, l2, l3, l4) END, E'\n' ORDER BY col), '') AS field_presence_rows,
       coalesce(bool_or(hide) FILTER (WHERE col LIKE 'User.%'), false) AS suppress_user_counts
FROM p
\gset
\qecho :field_presence_rows

-- ---------------------------------------------------------------------------------------------
\qecho
\qecho '## SH-08 Users, Roles And Home Locations'
\qecho
\qecho 'Counts are suppressed when User field-presence counts are suppressed, so these distributions cannot reconstruct the withheld User total or boolean/rank counts.'
\qecho
\qecho 'Measure | Value | Users'
\qecho '--- | --- | ---:'
WITH u AS (
    SELECT u.*, (SELECT count(*) FROM "UserRole" ur WHERE ur."UserId" = u."Id" AND ur."ExpiryDate" IS NULL) AS roles
    FROM "User" u
), m AS (
    SELECT 1 AS o, 'Discriminator / enabled' AS k, "Discriminator" || ' / ' || CASE WHEN "IsEnabled" THEN 'enabled' ELSE 'disabled' END AS v, count(*) AS n FROM u GROUP BY 3
    UNION ALL SELECT 2, 'Live roles per user', roles::text, count(*) FROM u GROUP BY 3
    UNION ALL SELECT 3, 'Live role held', r."Name", count(DISTINCT ur."UserId") FROM "UserRole" ur JOIN "Role" r ON r."Id" = ur."RoleId" WHERE ur."ExpiryDate" IS NULL GROUP BY 3
    UNION ALL SELECT 4, 'Rank text (enabled sheriffs)', v, sum(n)::bigint FROM (
        SELECT CASE WHEN count(*) >= 5 THEN coalesce("Rank", '(null)') ELSE '(other values, each under 5 users)' END AS v, count(*) AS n
        FROM u WHERE "Discriminator" = 'Sheriff' AND "IsEnabled" GROUP BY "Rank") rk GROUP BY v
    UNION ALL SELECT 5, 'Enabled sheriffs per home location (band)', b, count(*) FROM (
        SELECT CASE WHEN n < 5 THEN '01 1-4' WHEN n < 10 THEN '02 5-9' WHEN n < 25 THEN '03 10-24' WHEN n < 50 THEN '04 25-49' WHEN n < 100 THEN '05 50-99' ELSE '06 100+' END AS b
        FROM (SELECT "HomeLocationId", count(*) AS n FROM u WHERE "Discriminator" = 'Sheriff' AND "IsEnabled" GROUP BY 1) h) hb GROUP BY 3
)
SELECT k, v, CASE WHEN :'suppress_user_counts'::boolean THEN 'suppressed' ELSE :sup END FROM m ORDER BY o, v;

ROLLBACK;
